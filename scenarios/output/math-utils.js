
// 数学工具库实现

/**
 * 加法运算
 * @param {number} a - 第一个数
 * @param {number} b - 第二个数
 * @returns {number} 两数之和
 */
export function add(a, b) {
  return a + b;
}

/**
 * 乘法运算
 * @param {number} a - 第一个数
 * @param {number} b - 第二个数
 * @returns {number} 两数之积
 */
export function multiply(a, b) {
  return a * b;
}

/**
 * 减法运算
 * @param {number} a - 第一个数
 * @param {number} b - 第二个数
 * @returns {number} 两数之差
 */
export function subtract(a, b) {
  return a - b;
}

/**
 * 除法运算
 * @param {number} a - 被除数
 * @param {number} b - 除数
 * @returns {number} 两数之商
 */
export function divide(a, b) {
  if (b === 0) {
    throw new Error('Division by zero');
  }
  return a / b;
}

